def predict(s):
    p = sum(1 for w in POS if w in s)
    n = sum(1 for w in NEG if w in s)
    if p > n: return P
    if n > p: return N
    return U

df = pd.DataFrame(data, columns=["sent","gold"])
df["pred"] = df["sent"].apply(predict)

print(f"파일럿 문장 수: {len(df)}")
print("\n== 사람 라벨 분포 ==")
d = df["gold"].value_counts()
for k in [P,U,N]:
    print(f"  {k}: {d.get(k,0):>3}건  ({d.get(k,0)/len(df)*100:.1f}%)")

maj = d.max()/len(df)
print(f"\n다수 클래스 기준선(전부 '{d.idxmax()}'이라 답하기) 정확도 = {maj:.3f}")

acc = (df.gold==df.pred).mean()
print(f"소형 사전 기반 베이스라인 정확도      = {acc:.3f}")

print("\n== 혼동행렬 (행=정답, 열=예측) ==")
cm = pd.crosstab(df["gold"], df["pred"]).reindex(index=[P,U,N], columns=[P,U,N]).fillna(0).astype(int)
print(cm.to_string())

print("\n== 클래스별 지표 ==")
print(f"{'클래스':<6}{'정밀도':>8}{'재현율':>8}{'F1':>8}{'실제수':>8}")
f1s=[]
for k in [P,U,N]:
    tp = ((df.gold==k)&(df.pred==k)).sum()
    fp = ((df.gold!=k)&(df.pred==k)).sum()
    fn = ((df.gold==k)&(df.pred!=k)).sum()
    prec = tp/(tp+fp) if tp+fp else 0.0
    rec  = tp/(tp+fn) if tp+fn else 0.0
    f1   = 2*prec*rec/(prec+rec) if prec+rec else 0.0
    f1s.append(f1)
    print(f"{k:<6}{prec:>8.3f}{rec:>8.3f}{f1:>8.3f}{(df.gold==k).sum():>8}")
print(f"\nmacro-F1 (세 클래스 F1의 단순 평균) = {sum(f1s)/3:.3f}")
print(f"micro-F1 (= 정확도)                 = {acc:.3f}")
w = sum(f1*(df.gold==k).sum() for f1,k in zip(f1s,[P,U,N]))/len(df)
print(f"weighted-F1                         = {w:.3f}")

print("\n== 사전이 놓친 부정 문장(재현율 손실의 정체) ==")
