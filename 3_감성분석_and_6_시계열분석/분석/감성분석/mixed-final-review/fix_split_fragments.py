def fail(msg):
    sys.exit(f"[중단] {msg}")


def squash(s):
    return "".join(str(s).split())


def main():
    if not XLSX.exists():
        fail("혼합227_최종검토용.xlsx 가 없다.")
    base = pd.read_csv(BASE_CSV, encoding="utf-8-sig", dtype=str).fillna("")
    sent_of = dict(zip(base["검토_id"], base["sent"]))
    cur = pd.read_excel(XLSX, sheet_name="검토", dtype=str).fillna("")

    unknown = set(FIX) - set(sent_of)
    if unknown:
        fail(f"대상에 없는 검토_id: {sorted(unknown)}")

    # 지금 실제로 깨져 있는 행과 보정 목록이 일치하는지 — 초벌이 다시 바뀌었으면 멈춘다
    sp = cur[cur["GPT_판정"] == "분할"]
    broken = set(sp.loc[(sp["GPT_분할1"] + sp["GPT_분할2"]).map(squash)
                        != sp["sent"].map(squash), "검토_id"])
    if broken != set(FIX):
        fail(f"깨진 행 목록이 다르다. 현재 {len(broken)}건 / 보정표 {len(FIX)}건\n"
             f"     보정표에만: {sorted(set(FIX) - broken)[:10]}\n"
             f"     현재에만  : {sorted(broken - set(FIX))[:10]}\n"
             "     GPT 초벌이 새로 바뀐 것 같다. 보정표를 다시 만든다.")

    rows = []
    for cid, (anchor, l1, l2, warn, memo) in FIX.items():
        sent = sent_of[cid]
        n = sent.count(anchor)
        if n == 0:
            fail(f"{cid}: 앵커 {anchor!r} 가 원문에 없다.")
        if n > 1:
            fail(f"{cid}: 앵커 {anchor!r} 가 원문에 {n}번 나온다 — 자를 지점이 모호하다.")
        cut = sent.index(anchor) + len(anchor)
        p1, p2 = sent[:cut].strip(), sent[cut:].strip()
        if not p1 or not p2:
            fail(f"{cid}: 조각 하나가 빈다.")
        if squash(p1 + p2) != squash(sent):
            fail(f"{cid}: 조각을 이어 붙여도 원문이 아니다.")
        old = cur.loc[cur["검토_id"] == cid].iloc[0]
        rows.append({
            "검토_id": cid, "unit_id": old["unit_id"], "sent": sent,
            "이전_분할1": old["GPT_분할1"], "이전_분할2": old["GPT_분할2"],
            "이전_분할1_라벨": old["GPT_분할1_라벨"], "이전_분할2_라벨": old["GPT_분할2_라벨"],
            "보정_분할1": p1, "보정_분할1_라벨": l1,
            "보정_분할2": p2, "보정_분할2_라벨": l2,
            "주의": warn, "메모": memo,
        })

    log = pd.DataFrame(rows)
    log.to_csv(OUT_LOG, index=False, encoding="utf-8-sig")

    BACKUP_DIR.mkdir(exist_ok=True)
    stamp = datetime.now().strftime("%Y%m%d-%H%M%S")
    dest = BACKUP_DIR / stamp
    dest.mkdir(exist_ok=True)
    shutil.copy2(XLSX, dest / XLSX.name)

    try:
        wb = load_workbook(XLSX)
    except PermissionError:
        fail(f"{XLSX.name} 를 열 수 없다. Excel 에서 닫고 다시 실행한다.")
    ws = wb["검토"]
    head = {c.value: c.column for c in ws[1]}
    by_id = {r["검토_id"]: r for r in rows}
    touched = 0
    for i in range(2, ws.max_row + 1):
        cid = ws.cell(row=i, column=head["검토_id"]).value
        if cid not in by_id:
            continue
        r = by_id[cid]
        if ws.cell(row=i, column=head["GPT_판정"]).value != "분할":
            fail(f"{cid}: xlsx 의 판정이 `분할` 이 아니다.")
        ws.cell(row=i, column=head["GPT_분할1"]).value = r["보정_분할1"]
        ws.cell(row=i, column=head["GPT_분할1_라벨"]).value = r["보정_분할1_라벨"]
        ws.cell(row=i, column=head["GPT_분할2"]).value = r["보정_분할2"]
        ws.cell(row=i, column=head["GPT_분할2_라벨"]).value = r["보정_분할2_라벨"]
        touched += 1
    if touched != len(FIX):
        fail(f"{touched}행만 찾았다 — {len(FIX)}행을 기대했다.")
    try:
        wb.save(XLSX)
    except PermissionError:
        fail(f"{XLSX.name} 에 쓸 수 없다. Excel 에서 닫고 다시 실행한다.")

    warn_n = (log["주의"] == "주의").sum()
    print(f"분할 조각 {touched}행 보정 -> {XLSX.name} `검토` 시트")
    print(f"  GPT_판정 은 건드리지 않았다. 조각 원문과 조각 라벨만 갱신했다.")
    print(f"  주의 표시 {warn_n}건 — 사람이 이 행부터 본다:")
    for r in log[log["주의"] == "주의"].itertuples():
        print(f"    {r.검토_id}  {r.메모}")
    print(f"\n  기록: {OUT_LOG.name}")
    print(f"  백업: 백업/{stamp}/{XLSX.name}")
    print("\n다음: check_review.py 로 조각 정합성을 다시 확인한다.")


if __name__ == "__main__":
    main()
